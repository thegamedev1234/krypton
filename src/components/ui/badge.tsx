import type { ReactNode } from "react";
import { cn } from "@/lib/utils";

type BadgeTone = "neutral" | "accent" | "violet" | "ice" | "positive" | "warning" | "danger";

const TONES: Record<BadgeTone, string> = {
  neutral: "border-line bg-raised text-muted",
  accent: "border-accent/25 bg-accent/10 text-accentStrong",
  violet: "border-violet/25 bg-violet/10 text-violet",
  ice: "border-ice/25 bg-ice/10 text-ice",
  positive: "border-positive/25 bg-positive/10 text-positive",
  warning: "border-warning/25 bg-warning/10 text-warning",
  danger: "border-danger/25 bg-danger/10 text-danger",
};

interface BadgeProps {
  children: ReactNode;
  tone?: BadgeTone;
  icon?: ReactNode;
  className?: string;
  title?: string;
}

export function Badge({ children, tone = "neutral", icon, className, title }: BadgeProps) {
  return (
    <span
      title={title}
      className={cn(
        "inline-flex items-center gap-1 rounded-full border px-1.5 py-0.5 text-2xs font-medium leading-4",
        TONES[tone],
        className,
      )}
    >
      {icon}
      {children}
    </span>
  );
}

export function DemoBadge({ className }: { className?: string }) {
  return (
    <Badge
      tone="neutral"
      className={className}
      title="Pre-written local sample content — not generated by a model."
    >
      Demo
    </Badge>
  );
}

export function ComingSoonBadge({ className }: { className?: string }) {
  return (
    <Badge tone="warning" className={className}>
      Coming soon
    </Badge>
  );
}

export function StatusDot({ tone = "positive" }: { tone?: BadgeTone }) {
  const colors: Record<BadgeTone, string> = {
    neutral: "bg-faint",
    accent: "bg-accent",
    violet: "bg-violet",
    ice: "bg-ice",
    positive: "bg-positive",
    warning: "bg-warning",
    danger: "bg-danger",
  };
  return <span className={cn("h-1.5 w-1.5 rounded-full", colors[tone])} aria-hidden="true" />;
}
